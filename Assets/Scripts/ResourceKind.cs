// Перечисляет возможные находки и отсутствие ресурса.
public enum ResourceKind
{  // Начало перечисления `ResourceKind`.
    // Задаёт значение перечисления «отсутствие ресурса».
    None,
    // Задаёт значение перечисления «камень».
    Stone,
    // Задаёт значение перечисления «уголь».
    Coal,
    // Задаёт значение перечисления «медь».
    Copper,
    // Задаёт значение перечисления «железо».
    Iron,
    // Задаёт значение перечисления «золото».
    Gold,
    // Задаёт значение перечисления «клад».
    Treasure
}  // Конец перечисления `ResourceKind`.

// Задаёт цену продажи и русское имя ресурса.
public static class ResourceInfo
{  // Начало класса `ResourceInfo`.
    // Возвращает цену продажи одной единицы указанного ресурса.
    public static int Price(ResourceKind kind)
    {  // Начало метода `Price`.
        // Выбирает ветку по значению `kind`.
        switch (kind)
        {  // Начало выбора по значению.
            // Обрабатывает значение камень. Возвращает `1`.
            case ResourceKind.Stone: return 1;
            // Обрабатывает значение уголь. Возвращает `2`.
            case ResourceKind.Coal: return 2;
            // Обрабатывает значение медь. Возвращает `5`.
            case ResourceKind.Copper: return 5;
            // Обрабатывает значение железо. Возвращает `15`.
            case ResourceKind.Iron: return 15;
            // Обрабатывает значение золото. Возвращает `40`.
            case ResourceKind.Gold: return 40;
            // Обрабатывает все остальные значения. Возвращает `0`.
            default: return 0;
        }  // Конец выбора по значению.
    }  // Конец метода `Price`.

    // Возвращает название ресурса для интерфейса.
    public static string Title(ResourceKind kind)
    {  // Начало метода `Title`.
        // Выбирает ветку по значению `kind`.
        switch (kind)
        {  // Начало выбора по значению.
            // Обрабатывает значение камень. Возвращает `"Камень"`.
            case ResourceKind.Stone: return "Камень";
            // Обрабатывает значение уголь. Возвращает `"Уголь"`.
            case ResourceKind.Coal: return "Уголь";
            // Обрабатывает значение медь. Возвращает `"Медь"`.
            case ResourceKind.Copper: return "Медь";
            // Обрабатывает значение железо. Возвращает `"Железо"`.
            case ResourceKind.Iron: return "Железо";
            // Обрабатывает значение золото. Возвращает `"Золото"`.
            case ResourceKind.Gold: return "Золото";
            // Обрабатывает значение клад. Возвращает `"Клад"`.
            case ResourceKind.Treasure: return "Клад";
            // Обрабатывает все остальные значения. Возвращает `""`.
            default: return "";
        }  // Конец выбора по значению.
    }  // Конец метода `Title`.
}  // Конец класса `ResourceInfo`.
