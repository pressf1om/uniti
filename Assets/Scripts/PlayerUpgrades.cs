// Задаёт стоимость, названия и предельный уровень улучшений прыжка.
public static class PlayerUpgrades
{  // Начало класса `PlayerUpgrades`.
    /// <summary>Стоимость перехода на уровень прыжка 1..3 (двойной, тройной, четверной).</summary>
    public static readonly int[] JumpBootsCost = { 0, 120, 500, 2000 };  // Задаёт цены уровней дополнительных прыжков `JumpBootsCost` массивом `{ 0, 120, 500, 2000 }`.
    // Задаёт предельный уровень дополнительных прыжков `MaxJumpBootsLevel` значением `3`.
    public const int MaxJumpBootsLevel = 3;

    // Возвращает название улучшения для следующего уровня.
    public static string JumpBootsCaption(int nextLevel)
    {  // Начало метода `JumpBootsCaption`.
        // Выбирает ветку по значению `nextLevel`.
        switch (nextLevel)
        {  // Начало выбора по значению.
            // Обрабатывает значение `1`. Возвращает `"Двойной прыжок"`.
            case 1: return "Двойной прыжок";
            // Обрабатывает значение `2`. Возвращает `"Тройной прыжок"`.
            case 2: return "Тройной прыжок";
            // Обрабатывает значение `3`. Возвращает `"Четверной прыжок"`.
            case 3: return "Четверной прыжок";
            // Обрабатывает все остальные значения. Возвращает `"Прыжок"`.
            default: return "Прыжок";
        }  // Конец выбора по значению.
    }  // Конец метода `JumpBootsCaption`.
}  // Конец класса `PlayerUpgrades`.